function getIcon(iconName: string) {
  switch(iconName) {
    case 'home': return <HomeIcon />
    case 'database': return <DatabaseIcon />
    case 'upload': return <UploadIcon />
    case 'bar-chart': return <ChartIcon />
    case 'settings': return <SettingsIcon />
    default: return <HomeIcon />
  }
}

export function Sidebar() {
  const [collapsed, setCollapsed] = useState(false)
  const pathname = usePathname()

  return (
    <aside
      className={
        collapsed 
          ? 'w-[var(--sidebar-width-collapsed)] border-r bg-card transition-all duration-300 flex flex-col' 
          : 'w-[var(--sidebar-width)] border-r bg-card transition-all duration-300 flex flex-col'
      }
    >
      <div className="h-16 flex items-center justify-between px-4 border-b">
        {!collapsed && (
          <div className="flex items-center gap-2">
            <div className="w-8 h-8 rounded-lg bg-primary flex items-center justify-center">
              <span className="text-primary-foreground font-bold text-sm">BC</span>
            </div>
            <span className="font-semibold text-lg">Base Camp</span>
          </div>
        )}
        <button
          onClick={() => setCollapsed(!collapsed)}
          className="p-2 rounded-md hover:bg-muted transition-colors"
          aria-label={collapsed ? 'Expand sidebar' : 'Collapse sidebar'}
        >
          <svg
            className={collapsed ? 'w-5 h-5 transition-transform rotate-180' : 'w-5 h-5 transition-transform'}
            fill="none"
            stroke="currentColor"
            viewBox="0 0 24 24"
          >
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M11 19l-7-7 7-7m8 14l-7-7 7-7" />
          </svg>
        </button>
      </div>

      <nav className="flex-1 p-4 space-y-1">
        {navItems.map((item) => {
          const isActive = item.href === '/basecamp'
            ? pathname === '/basecamp'
            : pathname.startsWith(item.href)
          return (
            <Link
              key={item.href}
              href={item.href}
              className={
                isActive
                  ? 'flex items-center gap-3 px-3 py-2 rounded-md transition-colors bg-primary text-primary-foreground'
                  : 'flex items-center gap-3 px-3 py-2 rounded-md transition-colors hover:bg-muted text-muted-foreground hover:text-foreground'
              }
            >
              {getIcon(item.icon)}
              {!collapsed && <span>{item.label}</span>}
            </Link>
          )
        })}
      </nav>

      <div className="p-4 border-t">
        <div className={collapsed ? 'flex items-center gap-3 justify-center' : 'flex items-center gap-3'}>
          <div className="w-2 h-2 rounded-full bg-green-500 animate-pulse" />
          {!collapsed && (
            <div className="text-sm">
              <div className="font-medium">System Online</div>
              <div className="text-muted-foreground text-xs">All services operational</div>
            </div>
          )}
        </div>
      </div>
    </aside>
  )
}
